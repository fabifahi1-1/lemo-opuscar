"""SHOTLIST.md from the resolved timeline (out/timeline.json, written by tools/dump.mjs) — the same data the film is drawn from."""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
T = json.load(open(os.path.join(ROOT, 'out/timeline.json')))
VT = json.load(open(os.path.join(ROOT, 'script/vtime.json')))
fmt = lambda t: f'{int(t // 60)}:{t % 60:05.2f}'
def framing(cam, kind):
    if kind == 'moral': return 'full-frame card', 'locked'
    if kind == 'end': return 'wide (desk)', 'slow push in'
    if not cam: return '—', '—'
    z0 = cam[2]; z1 = cam[5] if len(cam) == 6 else z0
    sz = lambda z: 'extreme close-up' if z >= 4.6 else 'close-up' if z >= 3 else 'medium' if z >= 1.9 else 'medium-wide' if z >= 1.3 else 'wide'
    if len(cam) == 6:
        dx, dy = cam[3] - cam[0], cam[4] - cam[1]
        mv = 'push in' if z1 > z0 * 1.03 else 'pull out' if z1 < z0 / 1.03 else ''
        if abs(dy) > 300: mv = ('tilt down' if dy > 0 else 'tilt up') + (' + ' + mv if mv else '')
        elif abs(dx) > 60: mv = ('pan right' if dx > 0 else 'pan left') + (' + ' + mv if mv else '')
        return f'{sz(z0)} → {sz(z1)}' if sz(z0) != sz(z1) else sz(z0), mv or 'slow drift'
    return sz(z0), 'locked + parallax drift'
SOUND = {'clipclop2': 'clip-clop ×2', 'knock': 'knock', 'knock_big': 'KNOCK (big)', 'pick': 'pick', 'ding': 'ding', 'splash': 'splash', 'swish': 'swish', 'baa': 'baaa', 'taptap': 'tap tap', 'doorbell': 'doorbell tune', 'creak': 'door creak', 'roar': 'funny roar', 'eek': 'eeek', 'slide': 'slide whistle', 'poof': 'poof', 'squeak': 'squeak', 'tr_page': 'page turn', 'tr_wipe': 'brush wipe', 'tr_mist': 'mist whoosh'}
out = ['# Puss in Boots — Shot list', '',
       f'Generated by `tools/shotlist.py` from the film\'s own timeline. Film length **{fmt(T["dur"])}** · {len(T["shots"])} shots · {len(T["cards"])} word cards · {len(T["scenes"])} scenes (clips).', '',
       'Times are film time. Every shot starts on a word of the narration (see `js/shots.js`). Word cards cut in over the shot for about 3 s at the moment the word is said. Music cues: `mus_*` / `tune_*`.', '']
cards = T['cards']
for z in T['scenes']:
    out += [f'## Scene {z["sc"]}: {z["name"]}  ({fmt(z["t0"])} – {fmt(z["t1"])}, {z["f1"] - z["f0"]} frames)', '',
            '| # | Time | Dur | Place | Framing | Camera | Action | Word card / labels / effects | Sound | In |', '|---|---|---|---|---|---|---|---|---|---|']
    for i, s in enumerate(T['shots']):
        if s['sc'] != z['sc']: continue
        fr, mv = framing(s.get('cam'), s.get('kind'))
        cs = [c['text'] for c in cards if s['t0'] <= c['t0'] < s['t1']]
        fx = s.get('fx') or []
        snd = sorted({SOUND.get(e['type'], e['type']) for e in T['ev'] if s['t0'] <= e['t'] < s['t1'] and e['type'] not in ('card_in', 'card_out', 'type')})
        txt = '; '.join(([f'**card: {c}**' for c in cs]) + fx)
        out.append(f'| {i + 1} | {fmt(s["t0"])} | {s["t1"] - s["t0"]:.1f}s | {s.get("loc") or s.get("kind")} | {fr} | {mv} | {s.get("name", "")} | {txt} | {", ".join(snd)} | {s.get("tr") or "cut"} |')
    out.append('')
open(os.path.join(ROOT, 'SHOTLIST.md'), 'w').write('\n'.join(out))
print('SHOTLIST.md', len(T['shots']), 'shots')
